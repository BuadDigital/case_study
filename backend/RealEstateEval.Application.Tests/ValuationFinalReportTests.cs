/// <summary>
/// The final report: the approved report (frozen at approval) with the recorded deposit code in each page header and the
/// certificate page appended, generated by the server, stored in the attachments service next to the certificate, and
/// regenerated when the code is corrected. A renderer failure never undoes the code registration.
/// </summary>
public class ValuationFinalReportTests
{
    private const string AppraiserDistributionId = "val-abdullah";

    private static readonly ReportDraftActor Specialist = new() { UserId = "u-spec", PrototypeRole = "case-specialist" };
    private static readonly ReportDraftActor Supervisor = new() { UserId = "u-sup", PrototypeRole = "section-supervisor" };
    private static readonly ReportDraftActor Stranger = new() { UserId = "u-fi", PrototypeRole = "field-inspector" };
    private static readonly ReportDraftActor Appraiser = new()
    {
        UserId = "u-app", PrototypeRole = "real-estate-appraiser", DistributionAssigneeId = AppraiserDistributionId,
    };

    private const string ApprovedHtml =
        "<html><body>"
        + "<div class=\"pg-meta\">رقم التقرير: 047789<br>التاريخ: 2026/10/05<br>رمز إيداع التقرير:</div><p>p1</p>"
        + "<div class=\"pg-meta\">رقم التقرير: 047789<br>التاريخ: 2026/10/05<br>رمز إيداع التقرير: —</div><p>p2</p>"
        + "<div class=\"other\">رمز إيداع التقرير: keep</div>"
        + "</body></html>";

    // ---- the code line rewrite ----

    [Fact]
    public void The_code_is_written_into_every_page_header_and_nowhere_else()
    {
        var result = ReportDepositCodeRewriter.Apply(ApprovedHtml, "QYM-77");

        Assert.Equal(2, result.Replaced);
        Assert.Equal(2, CountOf(result.Html, "رمز إيداع التقرير: QYM-77</div>"));
        Assert.Contains("<div class=\"other\">رمز إيداع التقرير: keep</div>", result.Html);
        Assert.Contains("<p>p1</p>", result.Html);
        Assert.Contains("رقم التقرير: 047789<br>التاريخ: 2026/10/05<br>", result.Html);
    }

    [Fact]
    public void The_code_is_html_encoded_and_a_page_without_the_line_is_left_alone()
    {
        var encoded = ReportDepositCodeRewriter.Apply(ApprovedHtml, "A<b>&1");
        Assert.Contains("رمز إيداع التقرير: A&lt;b&gt;&amp;1</div>", encoded.Html);

        var none = ReportDepositCodeRewriter.Apply("<div class=\"pg-meta\">رقم التقرير: 1</div>", "X");
        Assert.Equal(0, none.Replaced);
    }

    // ---- the certificate goes to the attachments service ----

    [Fact]
    public async Task The_certificate_is_stored_in_the_attachments_service_and_the_copy_keeps_the_reference()
    {
        await using var rig = await ArrangeApprovedAsync();

        var (state, errors) = await rig.Service.RecordDepositAsync(rig.RequestId, Certificate("QYM-1"), Appraiser);
        Assert.Null(errors);
        Assert.Equal(ReportIssuanceStages.FinalIssued, state!.Stage);

        var stored = Assert.Single(rig.Files.Stored, f => f.Scope == ReportFileScopes.DepositCertificate);
        Assert.Equal($"{rig.PropertyId:D}:deposit:v1", stored.ScopeKey);
        Assert.Equal(TestPdf.OnePage, stored.Content);

        var row = await rig.Contexts.Valuation.ValuationReportIssuances.AsNoTracking().SingleAsync();
        Assert.Equal(stored.Id, row.CertificateAttachmentId);
        Assert.Null(row.CertificateContent);
        Assert.True(row.HasCertificate);
    }

    [Fact]
    public async Task A_failing_store_refuses_the_registration_and_records_nothing()
    {
        await using var rig = await ArrangeApprovedAsync();
        rig.Files.FailWith = "تعذّر حفظ الملف في خدمة المرفقات";

        var (_, errors) = await rig.Service.RecordDepositAsync(rig.RequestId, Certificate("QYM-1"), Appraiser);

        Assert.Equal("تعذّر حفظ الملف في خدمة المرفقات", errors!["certificateContentBase64"]);
        var row = await rig.Contexts.Valuation.ValuationReportIssuances.AsNoTracking().SingleAsync();
        Assert.Null(row.DepositCode);
        Assert.Null(row.FinalIssuedAtUtc);
    }

    [Fact]
    public async Task A_replacement_certificate_removes_the_one_it_replaced()
    {
        await using var rig = await ArrangeApprovedAsync();
        await rig.Service.RecordDepositAsync(rig.RequestId, Certificate("QYM-1"), Appraiser);
        var first = rig.Files.Stored.Single(f => f.Scope == ReportFileScopes.DepositCertificate).Id;

        var (_, errors) = await rig.Service.RecordDepositAsync(rig.RequestId, Certificate("QYM-1"), Appraiser);

        Assert.Null(errors);
        Assert.Contains(first, rig.Files.Deleted);
        var row = await rig.Contexts.Valuation.ValuationReportIssuances.AsNoTracking().SingleAsync();
        Assert.NotEqual(first, row.CertificateAttachmentId);
    }

    // ---- the final PDF ----

    [Fact]
    public async Task The_final_pdf_is_the_approved_report_with_the_code_plus_the_certificate_page()
    {
        await using var rig = await ArrangeApprovedAsync();

        var (state, errors) = await rig.Service.RecordDepositAsync(rig.RequestId, Certificate("QYM-1"), Appraiser);

        Assert.Null(errors);
        Assert.Equal(FinalReportStatuses.Ready, state!.FinalReportStatus);

        // The renderer got the approved HTML with the code in both headers.
        var html = Assert.Single(rig.Renderer.Rendered);
        Assert.Equal(2, CountOf(html, "رمز إيداع التقرير: QYM-1</div>"));

        // The merge joined the rendered report and the certificate, in that order.
        var merged = Assert.Single(rig.Merger.Merges);
        Assert.Equal(2, merged.Count);
        Assert.Equal(FakeRenderer.Pdf, merged[0]);
        Assert.Equal(TestPdf.OnePage, merged[1]);

        var final = Assert.Single(rig.Files.Stored, f => f.Scope == ReportFileScopes.FinalReport);
        Assert.Equal($"{rig.PropertyId:D}:final:v1", final.ScopeKey);
        Assert.Equal(FakeMerger.Merged, final.Content);

        var row = await rig.Contexts.Valuation.ValuationReportIssuances.AsNoTracking().SingleAsync();
        Assert.Equal(final.Id, row.FinalPdfAttachmentId);
        Assert.Equal("QYM-1", row.FinalPdfDepositCode);
        Assert.True(row.FinalPdfIsCurrent);
    }

    [Fact]
    public async Task A_current_final_pdf_is_not_generated_again()
    {
        await using var rig = await ArrangeApprovedAsync();
        await rig.Service.RecordDepositAsync(rig.RequestId, Certificate("QYM-1"), Appraiser);

        var status = await rig.FinalReports.EnsureGeneratedAsync(rig.RequestId);

        Assert.Equal(FinalReportStatuses.Ready, status);
        Assert.Single(rig.Renderer.Rendered);
    }

    [Fact]
    public async Task A_code_correction_regenerates_the_pdf_and_removes_the_stale_one()
    {
        await using var rig = await ArrangeApprovedAsync();
        await rig.Service.RecordDepositAsync(rig.RequestId, Certificate("QYM-1"), Appraiser);
        var stale = rig.Files.Stored.Single(f => f.Scope == ReportFileScopes.FinalReport).Id;

        var (state, errors) = await rig.Service.RecordDepositAsync(
            rig.RequestId, new RegisterDepositCertificateRequest { DepositCode = "QYM-2" }, Appraiser);

        Assert.Null(errors);
        Assert.Equal(FinalReportStatuses.Ready, state!.FinalReportStatus);
        Assert.Equal(2, rig.Renderer.Rendered.Count);
        Assert.Equal(2, CountOf(rig.Renderer.Rendered[1], "رمز إيداع التقرير: QYM-2</div>"));
        Assert.Contains(stale, rig.Files.Deleted);

        var row = await rig.Contexts.Valuation.ValuationReportIssuances.AsNoTracking().SingleAsync();
        Assert.Equal("QYM-2", row.FinalPdfDepositCode);
        Assert.NotEqual(stale, row.FinalPdfAttachmentId);
    }

    [Fact]
    public async Task A_renderer_failure_keeps_the_code_registered_and_can_be_retried()
    {
        await using var rig = await ArrangeApprovedAsync();
        rig.Renderer.Fail = true;

        var (state, errors) = await rig.Service.RecordDepositAsync(rig.RequestId, Certificate("QYM-1"), Appraiser);

        Assert.Null(errors);
        Assert.Equal(ReportIssuanceStages.FinalIssued, state!.Stage);
        Assert.Equal("QYM-1", state.DepositCode);
        Assert.Equal(FinalReportStatuses.Preparing, state.FinalReportStatus);
        Assert.DoesNotContain(rig.Files.Stored, f => f.Scope == ReportFileScopes.FinalReport);

        rig.Renderer.Fail = false;
        var (status, retryErrors) = await rig.Service.RegenerateFinalReportAsync(rig.RequestId, Specialist);

        Assert.Null(retryErrors);
        Assert.Equal(FinalReportStatuses.Ready, status);
        Assert.Contains(rig.Files.Stored, f => f.Scope == ReportFileScopes.FinalReport);
    }

