    [Fact]
    public async Task Another_role_or_another_appraiser_cannot_download_or_retry()
    {
        await using var rig = await ArrangeApprovedAsync();
        await rig.Service.RecordDepositAsync(rig.RequestId, Certificate("QYM-1"), Appraiser);
        var otherAppraiser = new ReportDraftActor
        {
            UserId = "u-app2", PrototypeRole = "real-estate-appraiser", DistributionAssigneeId = "val-someone-else",
        };

        foreach (var actor in new[] { Stranger, otherAppraiser })
        {
            var (file, errors) = await rig.Service.GetFinalReportAsync(rig.RequestId, actor);
            Assert.Null(file);
            Assert.Equal(ValuationReportDraftService.FinalReportForbiddenAr, errors![ReportDraftErrorKeys.Forbidden]);

            var (status, retryErrors) = await rig.Service.RegenerateFinalReportAsync(rig.RequestId, actor);
            Assert.Null(status);
            Assert.True(retryErrors!.ContainsKey(ReportDraftErrorKeys.Forbidden));
        }
    }

