    public static string Clip(string? value, string fallback, int max = 20000)
    {
        var t = (value ?? "").Trim();
        if (t.Length == 0) return fallback;
        return t.Length <= max ? t : t[..max];
    }

    public static IReadOnlyList<string> NormalizeLibrary(IEnumerable<string>? items)
    {
        var library = (items ?? [])
            .Select(x => (x ?? "").Trim())
            .Where(x => x.Length is > 0 and <= 2000)
            .Distinct(StringComparer.Ordinal)
            .Take(100)
            .ToList();
        return library.Count == 0 ? SpecialAssumptionLibrary.ToList() : library;
    }

