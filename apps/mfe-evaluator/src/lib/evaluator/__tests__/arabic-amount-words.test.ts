describe("amountToArabicWords — Arabic number grammar", () => {
  it.each(CASES)("%d → %s", (value, words) => {
    expect(amountToArabicWords(value)).toBe(words);
  });

  it("reads the report's rounded finals the way the testers expected", () => {
    expect(amountToArabicWords(2_000_000)).toBe("مليونا ريال سعودي");
    expect(amountToArabicWords(200_000)).toBe("مائتا ألف ريال سعودي");
    expect(amountToArabicWords(103_000)).toBe("مائة وثلاثة آلاف ريال سعودي");
    expect(amountToArabicWords(2_810_000)).toBe("مليونان وثمانمائة وعشرة آلاف ريال سعودي");
  });

  it("accepts Arabic digits and separators, and prints «—» for nothing", () => {
    expect(amountToArabicWords("٢٬٠٠٠٬٠٠٠")).toBe("مليونا ريال سعودي");
    expect(amountToArabicWords("")).toBe("—");
    expect(amountToArabicWords(-3_000)).toBe("سالب ثلاثة آلاف ريال سعودي");
  });

  it("carries 99.995 halalas into the next riyal", () => {
    expect(amountToArabicWords(1.999)).toBe("ريالان سعوديان");
  });
});
